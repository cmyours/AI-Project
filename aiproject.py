def run_async_safely(coro):
    """
    Colab/Jupyter에서 이미 이벤트 루프가 도는 경우가 있어서,
    async TTS 작업을 새 thread의 event loop에서 안전하게 실행함.
    일반 Python 스크립트에서는 asyncio.run으로 바로 실행함.
    """
    try:
        asyncio.get_running_loop()
    except RuntimeError:
        return asyncio.run(coro)

    result_box = {"value": None, "error": None}

    def runner():
        try:
            result_box["value"] = asyncio.run(coro)
        except Exception as e:
            result_box["error"] = e

    thread = threading.Thread(target=runner, daemon=True)
    thread.start()
    thread.join()

    if result_box["error"] is not None:
        raise result_box["error"]

    return result_box["value"]


class BaseTTSProvider:
    """
    TTS Provider 공통 인터페이스.
    나중에 edge-tts 대신 로컬 모델, Azure, CLOVA, Piper/MeloTTS 등을 붙일 때
    synthesize(text)만 같은 형태로 맞추면 됨.
    """

    def synthesize(self, text: str) -> Optional[Path]:
        raise NotImplementedError


class EdgeTTSProvider(BaseTTSProvider):
    def __init__(
        self,
        voice: str = TTS_VOICE,
        output_dir: str = TTS_OUTPUT_DIR,
        output_filename: str = TTS_OUTPUT_FILENAME,
        rate: str = TTS_RATE,
        volume: str = TTS_VOLUME,
        pitch: str = TTS_PITCH,
    ):
        self.voice = voice
        self.output_dir = Path(output_dir)
        self.output_filename = output_filename
        self.rate = rate
        self.volume = volume
        self.pitch = pitch

    def synthesize(self, text: str) -> Optional[Path]:
        text = str(text).strip()

        if not text:
            return None

        self.output_dir.mkdir(parents=True, exist_ok=True)
        output_path = self.output_dir / self.output_filename

        run_async_safely(
            self._save_mp3(
                text=text,
                output_path=output_path,
            )
        )

        return output_path

    async def _save_mp3(self, text: str, output_path: Path) -> None:
        communicate = edge_tts.Communicate(
            text=text,
            voice=self.voice,
            rate=self.rate,
            volume=self.volume,
            pitch=self.pitch,
        )
        await communicate.save(str(output_path))


class ElevenLabsTTSProvider(BaseTTSProvider):
    def __init__(
        self,
        api_key: str = ELEVENLABS_API_KEY,
        voice_id: str = ELEVENLABS_VOICE_ID,
        model_id: str = ELEVENLABS_MODEL_ID,
        output_format: str = ELEVENLABS_OUTPUT_FORMAT,
        output_dir: str = TTS_OUTPUT_DIR,
        output_filename: str = TTS_OUTPUT_FILENAME,
        fallback_to_edge: bool = ELEVENLABS_FALLBACK_TO_EDGE,
    ):
        self.api_key = str(api_key or "").strip()
        self.voice_id = str(voice_id or "").strip()
        self.model_id = str(model_id or "").strip()
        self.output_format = str(output_format or "mp3_44100_128").strip()
        self.output_dir = Path(output_dir)
        self.output_filename = output_filename
        self.fallback_to_edge = fallback_to_edge

        self.edge_fallback = EdgeTTSProvider(
            output_dir=output_dir,
            output_filename=output_filename,
        )

        if not self.api_key:
            raise RuntimeError(
                "ELEVENLABS_API_KEY가 비어 있음. Colab에서 API 키를 입력해야 해."
            )

        if not self.voice_id or self.voice_id == "여기에_네가_고른_voice_id":
            raise RuntimeError(
                "ELEVENLABS_VOICE_ID가 설정되지 않았어. 네가 고른 voice_id를 넣어줘."
            )

        from elevenlabs.client import ElevenLabs
        from elevenlabs import VoiceSettings

        self.client = ElevenLabs(api_key=self.api_key)
        self.VoiceSettings = VoiceSettings

    def synthesize(self, text: str) -> Optional[Path]:
        text = self.prepare_text_for_tts(text)

        if not text:
            return None

        self.output_dir.mkdir(parents=True, exist_ok=True)
        output_path = self.output_dir / self.output_filename

        try:
            voice_settings = self.VoiceSettings(
                stability=ELEVENLABS_STABILITY,
                similarity_boost=ELEVENLABS_SIMILARITY_BOOST,
                style=ELEVENLABS_STYLE,
                use_speaker_boost=ELEVENLABS_USE_SPEAKER_BOOST,
            )

            audio = self.client.text_to_speech.convert(
                voice_id=self.voice_id,
                model_id=self.model_id,
                text=text,
                output_format=self.output_format,
                voice_settings=voice_settings,
            )

            with open(output_path, "wb") as f:
                if isinstance(audio, (bytes, bytearray)):
                    f.write(audio)
                else:
                    for chunk in audio:
                        if chunk:
                            f.write(chunk)

            return output_path

        except Exception as e:
            print(f"[ElevenLabs TTS ERROR] {type(e).__name__}: {e}")

            if self.fallback_to_edge:
                print("[ElevenLabs TTS ERROR] edge-tts로 fallback.")
                return self.edge_fallback.synthesize(text)

            raise

    @staticmethod
    def prepare_text_for_tts(text: str) -> str:
        text = str(text or "").strip()

        replacements = {
            "AI": "에이아이",
            "API": "에이피아이",
            "TTS": "티티에스",
            "STT": "에스티티",
            "JSON": "제이슨",
        }

        for src, dst in replacements.items():
            text = text.replace(src, dst)

        # 괄호류는 읽을 때 어색해서 공백으로 정리
        text = text.replace("(", " ")
        text = text.replace(")", " ")
        text = text.replace("[", " ")
        text = text.replace("]", " ")

        text = re.sub(r"\s+", " ", text).strip()

        return text


