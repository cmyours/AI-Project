def find_nearest_hourly_index(hourly_times: list, current_time: str) -> int:
    if not hourly_times:
        return -1

    if current_time in hourly_times:
        return hourly_times.index(current_time)

    # Open-Meteo current.time은 보통 "YYYY-MM-DDTHH:MM" 형태라서
    # 같은 시간대 prefix만 맞아도 현재 시간대 강수확률로 사용.
    current_hour = str(current_time)[:13]
    for index, hour_text in enumerate(hourly_times):
        if str(hour_text)[:13] == current_hour:
            return index

    return 0


