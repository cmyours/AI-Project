class ModelOutputParser:
    @staticmethod
    def parse_bool(value) -> bool:
        if isinstance(value, bool):
            return value

        if isinstance(value, str):
            normalized = value.strip().lower()
            if normalized in ["true", "1", "yes", "y"]:
                return True
            if normalized in ["false", "0", "no", "n", ""]:
                return False

        if isinstance(value, int):
            return value != 0

        return False

    @staticmethod
    def parse(text: str) -> ModelDecision:
        cleaned = text.strip()

        try:
            data = ModelOutputParser.extract_json(cleaned)

            output = str(data.get("output", "")).strip()
            action_required = ModelOutputParser.parse_bool(
                data.get("action_required", False)
            )
            action_trigger = str(data.get("action_trigger", "NONE")).strip()
            action_argument = str(data.get("action_argument", "")).strip()

            if not output:
                output = cleaned

            if not action_trigger:
                action_trigger = "NONE"

            return ModelDecision(
                output=output,
                action_required=action_required,
                action_trigger=action_trigger,
                action_argument=action_argument,
            )

        except Exception:
            legacy = ModelOutputParser.parse_legacy_action_tag(cleaned)
            if legacy is not None:
                return legacy

            return ModelDecision(
                output=cleaned,
                action_required=False,
                action_trigger="NONE",
                action_argument="",
            )

    @staticmethod
    def parse_legacy_action_tag(text: str) -> Optional[ModelDecision]:
        cleaned = str(text or "").strip()

        tag_match = re.search(r"<<\s*([A-Z_]+)(?:\s*[-:]?\s*([^>]+?))?\s*>>", cleaned)
        if not tag_match:
            return None

        trigger = tag_match.group(1).strip()
        argument = (tag_match.group(2) or "").strip()

        output = re.sub(r"<<.*?>>", "", cleaned).strip()
        output = output or "확인해볼게."

        return ModelDecision(
            output=output,
            action_required=True,
            action_trigger=trigger,
            action_argument=argument,
        )

    @staticmethod
    def extract_json(text: str) -> dict:
        try:
            return json.loads(text)
        except json.JSONDecodeError:
            pass

        code_block_match = re.search(
            r"```(?:json)?\s*(\{.*?\})\s*```",
            text,
            flags=re.DOTALL,
        )
        if code_block_match:
            return json.loads(code_block_match.group(1))

        start = text.find("{")
        end = text.rfind("}")

        if start == -1 or end == -1 or start >= end:
            raise ValueError("JSON 객체를 찾지 못했어.")

        return json.loads(text[start:end + 1])


