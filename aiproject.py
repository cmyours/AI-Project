class AssistantApp:
    def __init__(
        self,
        input_provider,
        output_provider,
        engine: AssistantEngine,
    ):
        self.input_provider = input_provider
        self.output_provider = output_provider
        self.engine = engine

    def run(self):
        print("\nAI Assistant Colab MVP 시작")
        print("직접 입력하면 콘솔 질문으로 처리하고, 그냥 Enter만 누르면 마이크 녹음으로 들어가")
        print("마이크 녹음 중에는 콘솔 입력이 잠깐 멈추고, 끝나면 다시 입력 가능해")
        print("종료하려면 exit, quit, 종료 중 하나를 입력해")
        print("DEBUG를 끄고 싶으면 코드 상단 DEBUG = False로 바꾸면 돼")
        print(f"입력 모드: {INPUT_MODE} / STT Provider: {STT_PROVIDER}")
        print(f"출력 모드: {OUTPUT_MODE} / TTS Provider: {TTS_PROVIDER}")

        while True:
            try:
                user_input = self.input_provider.get_input()
                text = user_input.text.strip()

                if not text:
                    continue

                if text.lower() in ["exit", "quit", "종료"]:
                    print("종료할게.")
                    break

                answer = self.engine.handle_user_text(text)

                if answer:
                    self.output_provider.send_output(answer)

            except KeyboardInterrupt:
                print("\n종료할게.")
                break

            except Exception as e:
                print(f"\n에러 발생: {e}")


