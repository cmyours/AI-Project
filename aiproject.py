    @classmethod
    def normalize(cls, decision: ModelDecision, user_text: str) -> ModelDecision:
        output = OutputSanitizer.sanitize(decision.output)
        trigger = str(decision.action_trigger or "NONE").strip()
        argument = str(decision.action_argument or "").strip()
        action_required = bool(decision.action_required)

        trigger = cls.TRIGGER_ALIASES.get(trigger, trigger)

        if trigger not in cls.ALLOWED_TRIGGERS:
            return ModelDecision(
                output=output or "아직 그 기능은 처리하기 어려워.",
                action_required=False,
                action_trigger="NONE",
                action_argument="",
            )

        if trigger == "NONE":
            return ModelDecision(
                output=output,
                action_required=False,
                action_trigger="NONE",
                action_argument="",
            )

        if trigger == "GET_CURRENT_TIME":
            return ModelDecision(
                output=output,
                action_required=True,
                action_trigger="GET_CURRENT_TIME",
                action_argument="",
            )

        if trigger == "GET_WEATHER":
            argument = cls.normalize_location(argument)

            if not argument:
                argument = cls.extract_location_from_user_text(user_text)

            if not argument or cls.has_ambiguous_location(argument):
                return ModelDecision(
                    output="지역이 어딘데? 알려주면 확인해볼게.",
                    action_required=False,
                    action_trigger="NONE",
                    action_argument="",
                )

            return ModelDecision(
                output=output or f"{argument} 날씨 확인해볼게.",
                action_required=True,
                action_trigger="GET_WEATHER",
                action_argument=argument,
            )

        if trigger == "SET_TIMER":
            parsed = TimerDurationParser.parse(argument) or TimerDurationParser.parse(user_text)

            if parsed is None:
                return ModelDecision(
                    output="타이머 시간을 정확히 말해줘. 예를 들면 10분이나 1시간 30분처럼.",
                    action_required=False,
                    action_trigger="NONE",
                    action_argument="",
                )

            _, normalized_duration = parsed

            return ModelDecision(
                output=output or f"{normalized_duration} 타이머 맞춰볼게.",
                action_required=True,
                action_trigger="SET_TIMER",
                action_argument=normalized_duration,
            )

        if trigger in {"ADD_SCHEDULE", "LIST_SCHEDULE"}:
            # 일정 action_argument는 JSON 문자열을 그대로 보존한다.
            # 실제 날짜 계산/검증은 ScheduleTool에서 담당한다.
            return ModelDecision(
                output=output,
                action_required=True,
                action_trigger=trigger,
                action_argument=argument or user_text,
            )

        return ModelDecision(
            output=output,
            action_required=False,
            action_trigger="NONE",
            action_argument="",
        )



