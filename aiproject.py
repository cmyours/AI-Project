        # 예전 습관대로 t:내용을 써도 동작하게 유지.
        if command.startswith("t:"):
            return UserInput(text=command[2:].strip(), source="keyboard")

        if command:
            return UserInput(text=command, source="keyboard")

        # 빈 입력이면 마이크 녹음 모드로 진입.
        # 이 구간에서는 콘솔 입력을 잠깐 받지 않고, 녹음/STT가 끝난 뒤 다시 프롬프트로 돌아감.
        try:
            audio_path = record_audio_in_colab(
                output_path=self.audio_path,
                seconds=self.record_seconds,
            )
            text = self.stt_provider.transcribe(audio_path)

            if not text:
                print("[STT] 인식된 텍스트가 비어 있어. 다시 Enter로 말하거나 직접 입력해줘.")
                return UserInput(text="", source="microphone")

            print(f"[STT] 인식 결과: {text}")
            return UserInput(text=text, source="microphone")

        except Exception as e:
            print(f"[STT ERROR] 음성 입력 실패: {type(e).__name__}: {e}")
            print("[STT ERROR] 이번 턴은 키보드 입력으로 fallback할게.")
            return self.keyboard_fallback.get_input()


