LLAMA_8B_EXPECTED_LORA_IN_FEATURES = 4096


def read_adapter_config(adapter_dir: Path) -> dict:
    config_path = adapter_dir / "adapter_config.json"

    if not config_path.exists():
        return {}

    try:
        return json.loads(config_path.read_text(encoding="utf-8"))
    except Exception:
        return {}


def adapter_base_model_name(adapter_dir: Path) -> str:
    config = read_adapter_config(adapter_dir)
    return str(config.get("base_model_name_or_path", "")).strip()


def looks_like_bllossom_adapter(adapter_dir: Path) -> bool:
    base_name = adapter_base_model_name(adapter_dir).lower()
    path_name = str(adapter_dir).lower()

    hints = [
        "bllossom",
        "llama-3-korean-bllossom",
        "llama",
    ]

    return any(hint in base_name for hint in hints) or any(
        hint in path_name for hint in ["bllossom", "llama"]
    )


def inspect_lora_input_dim(adapter_dir: Path) -> Optional[int]:
    """
    LoRA adapter weight shape를 직접 보고 base hidden size 호환성을 확인.

    Llama 3 8B/Bllossom 8B 쪽 q_proj LoRA A는 보통 shape가 [r, 4096]이야.
    만약 [r, 2048]이면 Qwen 1.5B 같은 다른 base용 adapter라서 붙이면 안 돼.
    """
    # 1) safetensors 우선
    safetensor_files = []
    preferred = adapter_dir / "adapter_model.safetensors"
    if preferred.exists():
        safetensor_files.append(preferred)
    safetensor_files.extend(
        p for p in adapter_dir.glob("*.safetensors") if p not in safetensor_files
    )

    for weight_path in safetensor_files:
        try:
            from safetensors import safe_open

            with safe_open(str(weight_path), framework="pt", device="cpu") as f:
                keys = list(f.keys())
                preferred_keys = [
                    k for k in keys
                    if "lora_A" in k and "q_proj" in k and "weight" in k
                ]
                fallback_keys = [
                    k for k in keys
                    if "lora_A" in k and "weight" in k
                ]

                for key in preferred_keys + fallback_keys:
                    shape = f.get_tensor(key).shape
                    if len(shape) == 2:
                        return int(shape[1])
        except Exception as e:
            print(f"adapter shape 검사 실패: {weight_path} / {e}")

    # 2) pytorch bin fallback
    bin_files = []
    preferred_bin = adapter_dir / "adapter_model.bin"
    if preferred_bin.exists():
        bin_files.append(preferred_bin)
    bin_files.extend(p for p in adapter_dir.glob("*.bin") if p not in bin_files)

    for weight_path in bin_files:
        try:
            state = torch.load(str(weight_path), map_location="cpu")
            preferred_keys = [
                k for k in state.keys()
                if "lora_A" in k and "q_proj" in k and "weight" in k
            ]
            fallback_keys = [
                k for k in state.keys()
                if "lora_A" in k and "weight" in k
            ]

            for key in preferred_keys + fallback_keys:
                tensor = state[key]
                if hasattr(tensor, "shape") and len(tensor.shape) == 2:
                    return int(tensor.shape[1])
        except Exception as e:
            print(f"adapter bin shape 검사 실패: {weight_path} / {e}")

    return None


def is_compatible_lora_adapter(adapter_dir: Path) -> Tuple[bool, str]:
    if not (adapter_dir / "adapter_config.json").exists():
        return False, "adapter_config.json 없음"

    base_name = adapter_base_model_name(adapter_dir)
    dim = inspect_lora_input_dim(adapter_dir)

    if dim is not None and dim != LLAMA_8B_EXPECTED_LORA_IN_FEATURES:
        return (
            False,
            f"LoRA input dim {dim} != Bllossom 8B expected {LLAMA_8B_EXPECTED_LORA_IN_FEATURES}",
        )

    if dim == LLAMA_8B_EXPECTED_LORA_IN_FEATURES:
        return True, f"shape OK dim={dim}, base={base_name or 'unknown'}"

    # shape를 못 읽는 경우에는 adapter_config/path 힌트로만 허용
    if looks_like_bllossom_adapter(adapter_dir):
        return True, f"shape 미확인, 이름상 Bllossom/Llama 후보, base={base_name or 'unknown'}"

    return False, f"Bllossom/Llama adapter로 보기 어려움, base={base_name or 'unknown'}"


def collect_lora_candidate_dirs(root_path: str) -> List[Path]:
    candidates: List[Path] = []

    def add_candidate(path: str | Path):
        candidate = Path(path)
        if (candidate / "adapter_config.json").exists() and candidate not in candidates:
            candidates.append(candidate)

    # 1. preferred
    add_candidate(PREFERRED_LORA_ADAPTER_PATH)

    # 2. latest path files
    for latest_file in LATEST_LORA_PATH_FILES:
        file_path = Path(latest_file)
        if not file_path.exists():
            continue

        value = file_path.read_text(encoding="utf-8").strip()
        if value:
            add_candidate(value)

    # 3. root and recursive adapters
    root = Path(root_path)
    if not root.exists():
        raise FileNotFoundError(f"LoRA 경로가 없어: {root_path}")

    add_candidate(root)

    for config_path in root.rglob("adapter_config.json"):
        add_candidate(config_path.parent)

    return candidates


def find_lora_adapter_dir(root_path: str) -> str:
    candidates = collect_lora_candidate_dirs(root_path)

    if not candidates:
        raise FileNotFoundError(
            f"LoRA adapter_config.json을 찾지 못함. 확인 경로: {root_path}"
        )

    compatible: List[Tuple[Path, str]] = []
    rejected: List[Tuple[Path, str]] = []

    for adapter_dir in candidates:
        ok, reason = is_compatible_lora_adapter(adapter_dir)
        if ok:
            compatible.append((adapter_dir, reason))
        else:
            rejected.append((adapter_dir, reason))

    print("\nLoRA adapter 후보 검사 결과:")
    for adapter_dir, reason in compatible:
        print(f"  [OK]   {adapter_dir} / {reason}")
    for adapter_dir, reason in rejected:
        print(f"  [SKIP] {adapter_dir} / {reason}")

    if not compatible:
        lines = [
            "Bllossom 8B와 호환되는 LoRA adapter를 찾지 못했어.",
            "지금 에러는 거의 확실히 다른 base model용 LoRA를 잡아서 생긴 거야.",
            f"필요 LoRA input dim: {LLAMA_8B_EXPECTED_LORA_IN_FEATURES}",
            "검사한 후보:",
        ]
        for adapter_dir, reason in rejected:
            lines.append(f"- {adapter_dir}: {reason}")
        raise RuntimeError("\n".join(lines))

    # preferred / latest / 이름 힌트 / 최신순 우선
    def priority(item: Tuple[Path, str]) -> Tuple[int, float]:
        adapter_dir, reason = item
        path_str = str(adapter_dir)
        score = 0

        if path_str == str(Path(PREFERRED_LORA_ADAPTER_PATH)):
            score += 100
        if "bllossom" in path_str.lower():
            score += 30
        if "shape OK" in reason:
            score += 50

        return (score, adapter_dir.stat().st_mtime)

    compatible.sort(key=priority, reverse=True)

    selected, reason = compatible[0]
    print(f"\nLoRA adapter 선택: {selected}")
    print(f"선택 이유: {reason}")

    return str(selected)

