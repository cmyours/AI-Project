class ElevenLabsSTTProvider:
    """
    ElevenLabs Speech to Text Provider.
    - 같은 ELEVENLABS_API_KEY를 사용
    - API 키에 Speech to Text 권한이 있어야 함
    """

    def __init__(
        self,
        api_key: str = ELEVENLABS_API_KEY,
        model_id: str = STT_MODEL_ID,
        language_code: str = STT_LANGUAGE_CODE,
        tag_audio_events: bool = STT_TAG_AUDIO_EVENTS,
        diarize: bool = STT_DIARIZE,
    ):
        self.api_key = str(api_key or "").strip()
        self.model_id = str(model_id or "scribe_v2").strip()
        self.language_code = str(language_code or "").strip()
        self.tag_audio_events = bool(tag_audio_events)
        self.diarize = bool(diarize)

        if not self.api_key:
            raise RuntimeError("ELEVENLABS_API_KEY가 없어서 ElevenLabs STT를 사용할 수 없어.")

        from elevenlabs.client import ElevenLabs
        self.client = ElevenLabs(api_key=self.api_key)

    def transcribe(self, audio_path: str | Path) -> str:
        audio_path = Path(audio_path)

        if not audio_path.exists():
            raise FileNotFoundError(f"녹음 파일이 없어: {audio_path}")

        audio_data = BytesIO(audio_path.read_bytes())
        audio_data.name = audio_path.name

        kwargs = {
            "file": audio_data,
            "model_id": self.model_id,
            "tag_audio_events": self.tag_audio_events,
            "diarize": self.diarize,
        }

        # Korean은 ElevenLabs 문서 기준 ISO-639-3 코드인 kor 사용.
        # 빈 문자열로 두면 자동 감지에 맡김.
        if self.language_code:
            kwargs["language_code"] = self.language_code

        result = self.client.speech_to_text.convert(**kwargs)

        text = getattr(result, "text", None)
        if text is None and isinstance(result, dict):
            text = result.get("text")

        text = str(text or "").strip()
        return text


class HybridConsoleMicInputProvider:
    """
    Colab 하이브리드 입력 Provider.
    - 문장을 그대로 입력하면 콘솔 입력으로 처리
    - Enter만 누르면 마이크 녹음 -> ElevenLabs STT -> 질문으로 처리
    - 마이크 녹음/STT 처리 중에는 콘솔 입력이 잠깐 비활성화되고, 처리 후 다시 콘솔로 돌아옴
    - exit / quit / 종료: 종료
    """

    def __init__(
        self,
        stt_provider: Optional[ElevenLabsSTTProvider] = None,
        record_seconds: float = VOICE_RECORD_SECONDS,
        audio_path: str = VOICE_AUDIO_PATH,
    ):
        self.stt_provider = stt_provider or ElevenLabsSTTProvider()
        self.record_seconds = float(record_seconds)
        self.audio_path = Path(audio_path)
        self.keyboard_fallback = KeyboardInputProvider()

    def get_input(self) -> UserInput:
        command = input(
            "\n직접 입력 / Enter=마이크 녹음 / exit=종료 > "
        ).strip()

        if command.lower() in ["exit", "quit", "종료"]:
            return UserInput(text=command, source="command")

