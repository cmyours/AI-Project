    @classmethod
    def is_schedule_add_intent(cls, text: str) -> bool:
        if cls.is_timer_intent(text) or cls.is_weather_intent(text):
            return False

        has_date = bool(ScheduleDateTimeParser.extract_date_text(text))
        has_time = bool(ScheduleDateTimeParser.extract_time_text(text))
        has_entity = cls.contains_any(text, cls.SCHEDULE_ENTITY_KEYWORDS)
        has_explicit_add = cls.has_explicit_schedule_add_intent(text)

        # "내일 오후 3시에 약속이 있는데 저장해줄래?"처럼
        # 질문문이어도 저장/메모/기록/추가 의도가 있으면 ADD가 우선이다.
        if has_explicit_add:
            return has_date or has_time or has_entity

        # 명시적 저장 동사가 없으면 조회 표현을 먼저 배제한다.
