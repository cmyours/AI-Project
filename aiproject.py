def build_prompt(messages: List[Dict[str, str]]) -> str:
    try:
        return tokenizer.apply_chat_template(
            messages,
            tokenize=False,
            add_generation_prompt=True,
        )
    except Exception:
        # Llama 3 계열 fallback 포맷
        parts = ["<|begin_of_text|>"]
        for msg in messages:
            role = msg["role"]
            content = msg["content"]
            if role not in {"system", "user", "assistant"}:
                role = "user"
            parts.append(
                f"<|start_header_id|>{role}<|end_header_id|>\n\n"
                f"{content}<|eot_id|>"
            )
        parts.append("<|start_header_id|>assistant<|end_header_id|>\n\n")
        return "".join(parts)


def generate_text(
    messages: List[Dict[str, str]],
    max_new_tokens: int = MAX_NEW_TOKENS,
    temperature: float = 0.3,
    top_p: float = 0.9,
) -> str:
    prompt = build_prompt(messages)

    inputs = tokenizer(
        prompt,
        return_tensors="pt",
    ).to(model.device)

    with torch.no_grad():
        # max_new_tokens와 모델 config의 max_length가 동시에 잡히는 경고를 피하려고
        # 총 길이 기준 max_length만 넘김.
        generation_max_length = inputs["input_ids"].shape[-1] + max_new_tokens

        output_ids = model.generate(
            **inputs,
            max_length=generation_max_length,
            do_sample=True,
            temperature=temperature,
            top_p=top_p,
            pad_token_id=tokenizer.pad_token_id,
            eos_token_id=get_eos_token_ids(tokenizer),
        )

    generated_ids = output_ids[0][inputs["input_ids"].shape[-1]:]

    text = tokenizer.decode(
        generated_ids,
        skip_special_tokens=True,
    )

    return text.strip()


