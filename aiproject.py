    @classmethod
    def classify_category(cls, raw_text: str, title: str = "") -> str:
        combined = f"{raw_text} {title}"

        for category, keywords in SCHEDULE_CATEGORY_KEYWORDS.items():
            if any(keyword in combined for keyword in keywords):
                return category

        return "기타"

    @classmethod
    def clean_schedule_title(cls, title: str, category: str = "기타") -> str:
        """
        모델이 뽑은 title을 그대로 믿지 않고 저장 직전에 한 번 더 정리한다.

        예:
        - "약속있는데, 해줄래" -> "약속"
        - "치과 예약 있는데 저장해줄래" -> "치과 예약"
        - "보고서 제출해야 해" -> "보고서 제출"
        """
        original = str(title or "").strip()
        category = cls.canonicalize_category(category or "기타")

        cleaned = original
        cleaned = cleaned.replace("，", " ").replace(",", " ")
        cleaned = cleaned.replace("?", " ").replace("!", " ")
        cleaned = re.sub(r"\s+", " ", cleaned).strip(" .,!?'\"“”‘’")

        # 문장 전체에 끼어드는 저장/요청성 노이즈를 제거한다.
        noise_patterns = [
            r"일정\s*저장\s*해\s*줘", r"일정\s*저장\s*해\s*줄래", r"일정에\s*넣어\s*줘",
            r"스케줄에\s*넣어\s*줘", r"캘린더에\s*넣어\s*줘", r"저장\s*해\s*줘",
            r"저장\s*해\s*줄래", r"저장\s*해\s*둬", r"저장\s*해", r"저장",
            r"메모\s*해\s*줘", r"메모\s*해\s*줄래", r"메모", r"기록\s*해\s*줘",
            r"기록\s*해\s*줄래", r"기록", r"등록\s*해\s*줘", r"등록",
            r"추가\s*해\s*줘", r"추가\s*해\s*줄래", r"추가", r"잡아\s*줘",
            r"해\s*줘", r"해\s*줄래", r"말해\s*줘", r"알려\s*줘",
            r"잊지\s*마", r"잊지말", r"기억\s*해\s*줘", r"기억\s*해\s*둬",
            r"있는데", r"있던데", r"있어", r"있음", r"잡혀\s*있어",
            r"해야\s*해", r"해야\s*돼", r"해야돼", r"해야겠다", r"할\s*거", r"하는\s*거",
        ]
        for pattern in noise_patterns:
            cleaned = re.sub(pattern, " ", cleaned)

        # 조사/군더더기 정리. 단어 내부 글자는 건드리지 않도록 공백 기준 표현만 처리한다.
        cleaned = re.sub(r"\b(나|내|좀)\b", " ", cleaned)
        cleaned = re.sub(r"\s+", " ", cleaned).strip(" .,!?'\"“”‘’")

        # 자주 나오는 명확한 제목은 짧게 정규화
        if "치과" in cleaned:
            return "치과 예약"
        if "건강검진" in cleaned:
            return "건강검진"
        if "병원" in cleaned:
            return "병원 일정"
        if "팀 회의" in cleaned:
            return "팀 회의"
        if "회의" in cleaned or "미팅" in cleaned:
            return cleaned[:40] if len(cleaned) >= 2 else "회의"
        if "약속" in cleaned:
            return "약속"
        if "식사" in cleaned or "밥" in cleaned:
            return cleaned[:40] if len(cleaned) >= 2 else "식사 약속"

        generic_titles = {
            "", "일정", "스케줄", "캘린더", "저장", "등록", "추가", "기록",
            "해줘", "해줄래", "있는데", "있어", "해야 해", "할일", "할 일",
        }
        if cleaned in generic_titles or len(cleaned) <= 1:
            fallback_by_category = {
                "약속": "약속",
                "회의": "회의",
                "병원": "병원 일정",
                "식사": "식사 약속",
                "업무": "업무 일정",
                "공부": "공부 일정",
                "운동": "운동 일정",
                "가족": "가족 일정",
                "이동": "이동 일정",
                "예약": "예약 일정",
                "할일": "할일",
                "기타": "일정",
            }
            return fallback_by_category.get(category, "일정")

        return cleaned[:40]

    @classmethod
    def resolve_event_fields(cls, data: Dict[str, Any], raw_text: str = "") -> Dict[str, Any]:
        raw = str(data.get("raw_text") or raw_text or "").strip()
        date_text = str(data.get("date_text") or "").strip() or cls.extract_date_text(raw)
        time_text = str(data.get("time_text") or "").strip() or cls.extract_time_text(raw)

        raw_title = str(data.get("title") or "").strip() or cls.extract_title(raw, date_text, time_text)
        raw_category = str(data.get("category") or "").strip()
        category = cls.canonicalize_category(raw_category)

        if category == "기타":
            category = cls.classify_category(raw, raw_title)

        title = cls.clean_schedule_title(raw_title, category=category)
        memo = str(data.get("memo") or "").strip()

        return {
            "date_text": date_text,
            "time_text": time_text,
            "category": category,
            "title": title,
            "memo": memo,
            "raw_text": raw,
        }

    @classmethod
    def format_korean_date_label(cls, date: str, reference: Optional[datetime] = None) -> str:
        reference = reference or cls.now()
        try:
            y, m, d = [int(part) for part in str(date).split("-")]
            target = datetime(y, m, d, tzinfo=reference.tzinfo).date()
            today = reference.date()

            if target == today:
                return "오늘"
            if target == today + timedelta(days=1):
                return "내일"
            if target == today + timedelta(days=2):
                return "모레"

            return f"{m}월 {d}일"
        except Exception:
            return str(date or "").strip()

    @classmethod
    def format_korean_time_value(cls, time_text: str) -> str:
        raw = str(time_text or "").strip()
        if not raw:
            return ""

        match = re.fullmatch(r"(\d{1,2}):(\d{2})", raw)
        if match:
            hour = int(match.group(1))
            minute = int(match.group(2))

            if hour == 0:
                base = "0시"
            elif hour < 12:
                base = f"오전 {hour}시"
            elif hour == 12:
                base = "오후 12시"
            else:
                base = f"오후 {hour - 12}시"

            if minute:
                return f"{base} {minute}분"
            return base

        return raw

    @classmethod
    def format_korean_datetime(cls, date: str, time_text: str = "") -> str:
        date_part = cls.format_korean_date_label(date)
        time_part = cls.format_korean_time_value(time_text)
        if time_part:
            return f"{date_part} {time_part}"
        return date_part


