class ScheduleStore:
    def __init__(self, file_path: str = SCHEDULE_EVENTS_FILE):
        self.file_path = Path(file_path)

    def load_events(self) -> List[Dict[str, Any]]:
        if not self.file_path.exists():
            return []

        try:
            data = json.loads(self.file_path.read_text(encoding="utf-8"))
            if isinstance(data, list):
                return data
            if isinstance(data, dict) and isinstance(data.get("events"), list):
                return data["events"]
        except Exception:
            return []

        return []

    def save_events(self, events: List[Dict[str, Any]]) -> None:
        self.file_path.parent.mkdir(parents=True, exist_ok=True)
        self.file_path.write_text(
            json.dumps(events, ensure_ascii=False, indent=2),
            encoding="utf-8",
        )

    def add_event(self, event: Dict[str, Any]) -> Dict[str, Any]:
        events = self.load_events()
        events.append(event)
        events.sort(key=lambda x: (x.get("date", ""), x.get("time", "99:99"), x.get("created_at", "")))
        self.save_events(events)
        return event

    def list_by_date(self, date_text: str) -> List[Dict[str, Any]]:
        events = self.load_events()
        return [event for event in events if event.get("date") == date_text]

    def list_between(self, start_date: str, end_date: str) -> List[Dict[str, Any]]:
        events = self.load_events()
        return [
            event for event in events
            if start_date <= str(event.get("date", "")) <= end_date
        ]


def normalize_schedule_event(event: Dict[str, Any]) -> Dict[str, Any]:
    normalized = dict(event or {})
    category = normalized.get("category") or "기타"
    normalized["category"] = ScheduleDateTimeParser.canonicalize_category(category)
    normalized["title"] = ScheduleDateTimeParser.clean_schedule_title(
        normalized.get("title") or normalized.get("category") or "일정",
        category=normalized.get("category") or "기타",
    )
    return normalized


def schedule_event_dedupe_key(event: Dict[str, Any]) -> Tuple[str, str, str, str]:
    normalized = normalize_schedule_event(event)
    return (
        str(normalized.get("date") or ""),
        str(normalized.get("time") or ""),
        str(normalized.get("category") or ""),
        str(normalized.get("title") or ""),
    )


def find_duplicate_schedule_event(
    events: List[Dict[str, Any]],
    new_event: Dict[str, Any],
) -> Optional[Dict[str, Any]]:
    new_key = schedule_event_dedupe_key(new_event)
    for event in events:
        if schedule_event_dedupe_key(event) == new_key:
            return normalize_schedule_event(event)
    return None


def dedupe_schedule_events(events: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    seen = set()
    deduped = []
    for event in events:
        normalized = normalize_schedule_event(event)
        key = schedule_event_dedupe_key(normalized)
        if key in seen:
            continue
        seen.add(key)
        deduped.append(normalized)
    return deduped


def format_schedule_event_for_result(event: Dict[str, Any]) -> str:
    normalized = normalize_schedule_event(event)
    date = normalized.get("date", "")
    time_value = normalized.get("time", "")
    title = normalized.get("title", "일정")
    if time_value:
        return f"{date} {time_value} {title}"
    return f"{date} 종일 {title}"


