class AssistantEngine:
    def __init__(self):
        self.memory = ConversationMemory(max_turns=6)
        self.action_router = ActionRouter()
        self.pending_weather_location = False
        self.pending_weather_question = ""

    def handle_user_text(self, user_text: str) -> str:
        user_text = user_text.strip()

        if not user_text:
            return ""

        pre_decision = PreActionRouter.route(
            user_text,
            pending_weather_location=self.pending_weather_location,
        )

        self.memory.add_user(user_text)

        if pre_decision is not None:
            decision = pre_decision
            decision = DecisionNormalizer.normalize(decision, user_text=user_text)
            if DEBUG:
                print("\n[DEBUG] 규칙 기반 선처리 판단")
                print(decision)
        else:
            decision = self.ask_model_for_decision(user_text)
            if DEBUG:
                print("\n[DEBUG] 1차 모델 판단")
                print(decision)

        if not decision.action_required:
            final_text = OutputSanitizer.sanitize(decision.output)
            self.update_pending_state(user_text, decision, final_text)
            self.memory.add_assistant(final_text)
            return final_text

        action_original_user_text = user_text
        if decision.action_trigger == "GET_WEATHER" and self.pending_weather_question:
            action_original_user_text = self.pending_weather_question

        action_result = self.action_router.run_action(decision)
        self.clear_pending_state()

        if DEBUG:
            print("\n[DEBUG] 액션 결과")
            print(action_result)

        if action_result is None:
            final_text = OutputSanitizer.sanitize(decision.output)
            self.memory.add_assistant(final_text)
            return final_text

        if not action_result.success:
            final_text = self.ask_model_with_action_result(
                original_user_text=action_original_user_text,
                action_result=action_result,
            )
            final_text = OutputSanitizer.sanitize(final_text)
            self.memory.add_assistant(final_text)
            return final_text

        if action_result.trigger == "SET_TIMER":
            final_text = self.format_timer_success(action_result)
            final_text = OutputSanitizer.sanitize(final_text)
            self.memory.add_assistant(final_text)
            return final_text

        if action_result.trigger == "ADD_SCHEDULE":
            final_text = self.format_schedule_add_success(action_result)
            final_text = OutputSanitizer.sanitize(final_text)
            self.memory.add_assistant(final_text)
            return final_text

        if action_result.trigger == "LIST_SCHEDULE":
            final_text = self.format_schedule_list_success(action_result)
            final_text = OutputSanitizer.sanitize(final_text)
            self.memory.add_assistant(final_text)
            return final_text

        final_text = self.ask_model_with_action_result(
            original_user_text=action_original_user_text,
            action_result=action_result,
        )

        final_text = OutputSanitizer.sanitize(final_text)
        self.memory.add_assistant(final_text)

        return final_text

    def update_pending_state(self, user_text: str, decision: ModelDecision, final_text: str) -> None:

        # 날씨 질문인데 지역이 없어서 되물은 경우, 다음 입력을 지역으로 받을 준비를 함.

        text = str(user_text or "")
        reply = str(final_text or "")

        asked_location = any(
            phrase in reply
            for phrase in [
                "지역이 어딘데",
                "지역 알려주면",
                "어디 날씨",
                "어느 지역",
                "지역을 알려주면",
            ]
        )

        if PreActionRouter.is_weather_intent(text) and asked_location:
            self.pending_weather_location = True
            self.pending_weather_question = text
            return

        self.clear_pending_state()

    def clear_pending_state(self) -> None:
        self.pending_weather_location = False
        self.pending_weather_question = ""

    def ask_model_for_decision(self, user_text: str) -> ModelDecision:
        messages = [
            {
                "role": "system",
                "content": SYSTEM_PROMPT,
            },
            *self.memory.get_messages(),
        ]

        raw = generate_text(
            messages,
            max_new_tokens=MAX_NEW_TOKENS,
            temperature=DECISION_TEMPERATURE,
            top_p=DECISION_TOP_P,
        )

        if DEBUG:
            print("\n[DEBUG] raw model output")
            print(raw)

        parsed = ModelOutputParser.parse(raw)
        normalized = DecisionNormalizer.normalize(parsed, user_text=user_text)

        return normalized

    def ask_model_with_action_result(
        self,
        original_user_text: str,
        action_result: ActionResult,
    ) -> str:
        instruction = (
            f"사용자 질문: {original_user_text}\n"
            f"{action_result.result_text}"
        )

        messages = [
            {
                "role": "system",
                "content": ACTION_RESULT_SYSTEM_PROMPT,
            },
            {
                "role": "user",
                "content": instruction,
            },
        ]

        raw = generate_text(
            messages,
            max_new_tokens=MAX_NEW_TOKENS,
            temperature=FINAL_TEMPERATURE,
            top_p=FINAL_TOP_P,
        )

        if DEBUG:
            print("\n[DEBUG] action response raw output")
            print(raw)

        decision = ModelOutputParser.parse(raw)
        final_text = decision.output

        if not final_text:
            final_text = self.fallback_action_response(original_user_text, action_result)

        return final_text

    def fallback_action_response(
        self,
        original_user_text: str,
        action_result: ActionResult,
    ) -> str:
        if action_result.success:
            if action_result.trigger == "GET_CURRENT_TIME" and action_result.raw:
                return self.format_time_fallback(original_user_text, action_result.raw)

            if action_result.trigger == "GET_WEATHER":
                return "날씨 결과를 가져왔는데 답변을 정리하는 데 문제가 생겼어. 잠시 후에 다시 물어봐줘."

            if action_result.trigger == "SET_TIMER":
                return self.format_timer_success(action_result)

            if action_result.trigger == "ADD_SCHEDULE":
                return self.format_schedule_add_success(action_result)

            if action_result.trigger == "LIST_SCHEDULE":
                return self.format_schedule_list_success(action_result)

        return self.format_error_fallback(action_result)

    def format_time_fallback(self, user_text: str, raw: Dict[str, Any]) -> str:
        current_time = raw.get("current_time", "")
        date_text = raw.get("date", "")
        weekday = raw.get("weekday", "")
        ampm = raw.get("ampm", "")

        if date_text:
            try:
                y, m, d = date_text.split("-")
                formatted_date = f"{int(y)}년 {int(m)}월 {int(d)}일"
            except Exception:
                formatted_date = date_text
        else:
            formatted_date = ""

        if "요일" in user_text and weekday:
            return f"오늘은 {weekday}이야."

        if any(word in user_text for word in ["날짜", "며칠", "몇 월", "몇월", "몇 일", "몇일"]):
            return f"오늘은 {formatted_date}이야."

        if current_time:
            hour, minute = current_time.split(":")
            return f"지금은 {int(hour)}시 {int(minute)}분이야."

        if ampm:
            return f"지금은 {ampm}이야."

        return "시간 정보를 가져왔는데 답변을 정리하지 못했어."

    def format_timer_success(self, action_result: ActionResult) -> str:
        raw = action_result.raw or {}
        duration = raw.get("duration") or "지정한 시간"
        return f"{duration} 타이머 맞춰놨어."

    def format_schedule_add_success(self, action_result: ActionResult) -> str:
        event = normalize_schedule_event(action_result.raw or {})
        status = event.get("status") or "SAVED"
        title = event.get("title") or event.get("category") or "일정"
        date = event.get("date") or ""
        time_value = event.get("time") or ""
        when = ScheduleDateTimeParser.format_korean_datetime(date, time_value)

        if status == "ALREADY_EXISTS":
            return f"{when}에 {title}, 이미 저장돼 있어."

        return f"{when}에 {title} 저장해뒀어."

    def format_schedule_list_success(self, action_result: ActionResult) -> str:
        raw = action_result.raw or {}
        events = dedupe_schedule_events(raw.get("events") or [])
        scope = raw.get("scope") or ""
        category = raw.get("category") or ""

        if not events:
            category_text = f" {category} 일정" if category else " 일정"
            if scope == "전체":
                return f"저장된{category_text}은 없어."
            if "~" in scope:
                return f"그 기간에 저장된{category_text}은 없어."
            try:
                y, m, d = scope.split("-")
                return f"{int(m)}월 {int(d)}일에는 저장된{category_text}이 없어."
            except Exception:
                return f"저장된{category_text}은 없어."

        lines = []
        for event in events[:8]:
            title = event.get("title") or event.get("category") or "일정"
            date = event.get("date") or ""
            time_value = event.get("time") or ""
            when = ScheduleDateTimeParser.format_korean_datetime(date, time_value)
            if time_value:
                lines.append(f"{when}에 {title}")
            else:
                lines.append(f"{when} 종일 {title}")

        if len(events) == 1:
            return f"{lines[0]} 있어."

        joined = ", ".join(lines)
        extra = f" 외 {len(events) - 8}개 더 있어" if len(events) > 8 else ""
        return f"일정은 {len(events)}개 있어. {joined}{extra}."

    def format_error_fallback(self, action_result: ActionResult) -> str:
        trigger = action_result.trigger
        error_code = action_result.error_code
        retryable = action_result.retryable

        if trigger == "GET_WEATHER":
            if error_code == "INVALID_ARGUMENT":
                return "지역을 제대로 못 알아들었어. 어느 지역 날씨인지 다시 말해줘."
            if retryable:
                return "날씨 정보를 가져오는 데 문제가 생겼어. 잠시 후에 다시 물어봐줘."
            return "지금은 날씨 정보를 가져오기 어렵네. 나중에 다시 물어봐줘."

        if trigger == "GET_CURRENT_TIME":
            if retryable:
                return "시간 정보를 가져오는 데 문제가 생겼어. 잠시 후에 다시 물어봐줘."
            return "지금은 시간 정보를 가져오기 어렵네."

        if trigger == "SET_TIMER":
            if error_code == "INVALID_ARGUMENT":
                return "타이머 시간을 제대로 못 알아들었어. 10분이나 1시간 30분처럼 다시 말해줘."
            if retryable:
                return "타이머 설정 중에 문제가 생겼어. 잠시 후에 다시 말해줘."
            return "지금은 타이머를 설정하기 어렵네."

        if trigger == "ADD_SCHEDULE":
            if error_code == "MISSING_DATE":
                return "어느 날짜 일정인지 모르겠어. 오늘, 내일, 이틀 뒤처럼 날짜를 같이 말해줘."
            if error_code == "MISSING_TIME":
                return "몇 시 일정인지 모르겠어. 오전 10시나 오후 2시처럼 다시 말해줘."
            return "일정을 저장하는 중에 문제가 생겼어. 다시 한번 말해줘."

        if trigger == "LIST_SCHEDULE":
            if error_code == "INVALID_DATE":
                return "어느 날짜 일정을 봐야 할지 모르겠어. 오늘, 내일, 금요일처럼 말해줘."
            return "일정을 확인하는 중에 문제가 생겼어. 잠시 후에 다시 물어봐줘."

        return "요청을 처리하는 중에 문제가 생겼어. 잠시 후에 다시 해보자."


