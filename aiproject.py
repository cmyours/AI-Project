class ListScheduleTool:
    def __init__(self):
        self.store = ScheduleStore()

    def run(self, argument: str) -> ActionResult:
        data = ScheduleDateTimeParser.parse_json_argument(argument, raw_text=argument)
        raw_text = str(data.get("raw_text") or argument)
        range_text = str(data.get("range_text") or "day").strip().lower()

        # action_argument가 부정확해도 raw_text 기준으로 보정한다.
        if any(word in raw_text for word in ["전체", "저장된", "모든", "전부", "지금까지"]):
            range_text = "all"
        elif any(word in raw_text for word in ["이번 달", "다음 달", "이달", "다음달", "이번달", "월간"]):
            range_text = "month"
        elif any(word in raw_text for word in ["이번 주", "다음 주", "주간", "일주일", "주말"]):
            range_text = "week"

        date_text = str(data.get("date_text") or "").strip() or ScheduleDateTimeParser.extract_date_text(raw_text)
        if not date_text and range_text != "all":
            date_text = "오늘"

        raw_category = str(data.get("category") or "").strip()
        category = ScheduleDateTimeParser.canonicalize_category(raw_category) if raw_category else ""
        if category == "기타" and not raw_category:
            category = ""

        reference = ScheduleDateTimeParser.now()

        if range_text == "all":
            events = self.store.load_events()
            scope_text = "전체"
        else:
            start_dt = ScheduleDateTimeParser.parse_date(date_text, reference=reference, allow_today_if_missing=True)

            if start_dt is None:
                return make_error_result("LIST_SCHEDULE", "INVALID_DATE", False)

            if range_text == "month":
                start_date = start_dt.date().replace(day=1)
                if start_date.month == 12:
                    next_month = start_date.replace(year=start_date.year + 1, month=1, day=1)
                else:
                    next_month = start_date.replace(month=start_date.month + 1, day=1)
                end_date = next_month - timedelta(days=1)
                events = self.store.list_between(start_date.isoformat(), end_date.isoformat())
                scope_text = f"{start_date.isoformat()}~{end_date.isoformat()}"
            elif range_text == "week" or any(word in raw_text for word in ["이번 주", "다음 주", "주간", "일주일", "주말"]):
                start_date = start_dt.date()
                # 특정 요일이 아니라 "이번 주" 자체면 그 주 월요일부터 일요일까지.
                if "주" in date_text and not re.search(r"[월화수목금토일](?:요일)?", date_text):
                    start_date = start_dt.date() - timedelta(days=start_dt.weekday())
                end_date = start_date + timedelta(days=6)
                events = self.store.list_between(start_date.isoformat(), end_date.isoformat())
                scope_text = f"{start_date.isoformat()}~{end_date.isoformat()}"
            else:
                target_date = start_dt.strftime("%Y-%m-%d")
                events = self.store.list_by_date(target_date)
                scope_text = target_date

        if category:
            events = [event for event in events if str(event.get("category") or "") == category]

        events = dedupe_schedule_events(events)
        event_texts = [format_schedule_event_for_result(event) for event in events]
        if event_texts:
            result_text = f"일정 조회 결과: 범위={scope_text}, 일정=" + " | ".join(event_texts)
        else:
            result_text = f"일정 조회 결과: 범위={scope_text}, 일정=없음"

        return ActionResult(
            success=True,
            trigger="LIST_SCHEDULE",
            result_text=result_text,
            raw={
                "scope": scope_text,
                "category": category,
                "range_text": range_text,
                "date_text": date_text,
                "events": events,
            },
        )


def make_error_result(trigger: str, error_code: str, retryable: bool) -> ActionResult:
    retryable_text = "true" if retryable else "false"
    result_text = (
        "액션 실행 결과: "
        f"action_trigger={trigger}, "
        "status=ERROR, "
        f"error_code={error_code}, "
        f"retryable={retryable_text}"
    )

    return ActionResult(
        success=False,
        trigger=trigger,
        result_text=result_text,
        raw=None,
        error_code=error_code,
        retryable=retryable,
    )


class ActionRouter:
    def __init__(self):
        self.tools = {
            "GET_CURRENT_TIME": CurrentTimeTool(),
            "GET_WEATHER": WeatherTool(),
            "SET_TIMER": TimerTool(),
            "ADD_SCHEDULE": AddScheduleTool(),
            "LIST_SCHEDULE": ListScheduleTool(),
        }

    def run_action(self, decision: ModelDecision) -> Optional[ActionResult]:
        if not decision.action_required:
            return None

        trigger = decision.action_trigger.strip()
        tool = self.tools.get(trigger)

        if tool is None:
            return make_error_result(
                trigger=trigger,
                error_code="UNKNOWN_ERROR",
                retryable=False,
            )

        try:
            return tool.run(decision.action_argument)
        except Exception:
            return make_error_result(
                trigger=trigger,
                error_code="UNKNOWN_ERROR",
                retryable=True,
            )


